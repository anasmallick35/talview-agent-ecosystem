#!/usr/bin/env bash
# The lesson ledger. One file per lesson, classified by where it can be enforced.
#
#   lesson.sh add <slug> <destination> <pr-url>    create from stdin (the lesson body)
#   lesson.sh bump <slug>                          seen again; 3+ flags for promotion
#   lesson.sh applied <slug> [note]                the enforcement now exists
#   lesson.sh list [status]
#   lesson.sh pending                              lessons needing a webclients PR
#   lesson.sh rules                                regenerate active-rules.md
#   lesson.sh queue add <pr-url> [repo]            a PR whose review is not harvested yet
#   lesson.sh queue list | queue done <pr-url>
#
# Destinations:
#   eslint-rule   mechanically detectable  -> dx/eslint-plugin       [webclients: PROPOSE]
#   hook          detectable at edit time  -> talview-core/hooks     [here: APPLY]
#   skill-rule    needs judgment           -> a skill's references/  [here: APPLY]
#   claude-md     seen 3+ times            -> CLAUDE.md              [webclients: PROPOSE]
#
# Storage lives in $HOME/.talview/lessons, NOT in the plugin directory. The plugin is
# installed into a version-pinned cache: writing lessons there means every release of
# this plugin silently abandons everything it learned. Override with TLV_LESSONS_DIR.

set -uo pipefail

: "${CLAUDE_PLUGIN_ROOT:=$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)}"
DIR="${TLV_LESSONS_DIR:-${TLV_HOME:-$HOME}/.talview/lessons}"
RULES="$DIR/active-rules.md"
QUEUE="$DIR/harvest-queue.json"
mkdir -p "$DIR"

# One-time migration from the old in-plugin location, so upgrading does not lose work.
legacy="${CLAUDE_PLUGIN_ROOT}/lessons"
if [ -d "$legacy" ] && [ "$legacy" != "$DIR" ]; then
  for old in "$legacy"/*.md; do
    [ -f "$old" ] || continue
    [ -f "$DIR/$(basename "$old")" ] || { cp "$old" "$DIR/"; echo "migrated $(basename "$old") out of the plugin cache" >&2; }
  done
fi

# The rules file is DERIVED. It is what a session actually reads, so it is regenerated
# from the ledger rather than hand-edited — a rule that drifts from its lesson is a rule
# with no evidence behind it.
regen_rules() {
  local n=0
  {
    echo "<!-- GENERATED by lesson.sh rules — do not edit. Source: $DIR/*.md -->"
    echo "# Rules learned from review"
    echo
    for f in "$DIR"/*.md; do
      [ -f "$f" ] || continue
      grep -q '^status: applied' "$f" || continue
      case "$(grep -m1 '^destination:' "$f" | cut -d' ' -f2-)" in
        skill-rule|claude-md) ;;
        *) continue ;;
      esac
      n=$((n+1))
      printf -- "- **%s** (seen %s, %s): %s\n" \
        "$(basename "$f" .md)" \
        "$(grep -m1 '^seen:' "$f" | cut -d' ' -f2-)" \
        "$(grep -m1 '^source:' "$f" | cut -d' ' -f2-)" \
        "$(awk '/^## Proposed enforcement/{f=1;next} /^## /{f=0} f && NF' "$f" | head -2 | tr '\n' ' ')"
    done
    [ "$n" -eq 0 ] && echo "_No applied rules yet._"
  } > "$RULES"
  echo "$n"
}

case "${1:-list}" in
  add)
    slug="${2:?slug}"; dest="${3:?destination}"; pr="${4:-}"
    case "$dest" in
      eslint-rule|claude-md) applies="propose" ;;
      hook|skill-rule)       applies="apply" ;;
      *) echo "unknown destination '$dest'" >&2; exit 64 ;;
    esac
    f="$DIR/$slug.md"
    [ -f "$f" ] && { echo "lesson '$slug' exists — bump its count instead:"; grep -m1 '^seen:' "$f"; exit 1; }
    { echo "---"
      echo "slug: $slug"
      echo "destination: $dest"
      echo "action: $applies"
      echo "status: open"
      echo "seen: 1"
      echo "source: ${pr}"
      echo "---"
      echo
      cat
    } > "$f"
    echo "recorded $slug -> $dest ($applies)  [$DIR]"
    [ "$applies" = "apply" ] && echo "  -> write the rule or hook now, then: lesson.sh applied $slug"
    ;;

  bump)
    f="$DIR/${2:?slug}.md"; [ -f "$f" ] || { echo "no such lesson" >&2; exit 1; }
    n=$(( $(grep -m1 '^seen:' "$f" | awk '{print $2}') + 1 ))
    sed -i '' "s/^seen: .*/seen: $n/" "$f" 2>/dev/null || sed -i "s/^seen: .*/seen: $n/" "$f"
    echo "$2 seen $n time(s)"
    [ "$n" -ge 3 ] && echo "  -> seen 3+ times: candidate for promotion to a CLAUDE.md hard rule."
    regen_rules >/dev/null
    ;;

  applied)
    f="$DIR/${2:?slug}.md"; [ -f "$f" ] || { echo "no such lesson" >&2; exit 1; }
    note="${3:-}"
    sed -i '' "s/^status: .*/status: applied/" "$f" 2>/dev/null || sed -i "s/^status: .*/status: applied/" "$f"
    [ -n "$note" ] && printf '\n## Enforcement landed\n%s\n' "$note" >> "$f"
    echo "$2 marked applied; $(regen_rules) rule(s) now active"
    ;;

  rules)
    n="$(regen_rules)"
    echo "$RULES — $n active rule(s)"
    ;;

  path) echo "$DIR" ;;

  queue)
    sub="${2:-list}"
    [ -f "$QUEUE" ] || echo '[]' > "$QUEUE"
    case "$sub" in
      add)
        url="${3:?pr url}"; repo="${4:-}"
        jq --arg u "$url" --arg r "$repo" \
          'if any(.[]; .url == $u) then . else . + [{url:$u, repo:$r, harvested:false}] end' \
          "$QUEUE" > "$QUEUE.tmp" && mv "$QUEUE.tmp" "$QUEUE"
        echo "queued for harvest once review lands: $url"
        ;;
      done)
        url="${3:?pr url}"
        jq --arg u "$url" 'map(if .url == $u then .harvested = true else . end)' \
          "$QUEUE" > "$QUEUE.tmp" && mv "$QUEUE.tmp" "$QUEUE"
        echo "marked harvested: $url"
        ;;
      list)
        jq -r '[.[] | select(.harvested == false)] | if length == 0 then "_nothing awaiting harvest_" else .[].url end' "$QUEUE"
        ;;
      count) jq -r '[.[] | select(.harvested == false)] | length' "$QUEUE" ;;
      *) echo "usage: lesson.sh queue add|list|done|count" >&2; exit 64 ;;
    esac
    ;;

  list)
    printf "%-34s %-14s %-9s %-6s %s\n" SLUG DESTINATION ACTION SEEN STATUS
    for f in "$DIR"/*.md; do
      [ -f "$f" ] || continue
      [ "$(basename "$f")" = "active-rules.md" ] && continue
      printf "%-34s %-14s %-9s %-6s %s\n" \
        "$(basename "$f" .md)" \
        "$(grep -m1 '^destination:' "$f" | cut -d' ' -f2-)" \
        "$(grep -m1 '^action:' "$f" | cut -d' ' -f2-)" \
        "$(grep -m1 '^seen:' "$f" | cut -d' ' -f2-)" \
        "$(grep -m1 '^status:' "$f" | cut -d' ' -f2-)"
    done
    ;;

  pending)
    echo "Lessons that need a change in the PRODUCT repo — these are proposals, not applied:"
    for f in "$DIR"/*.md; do
      [ -f "$f" ] || continue
      grep -q '^action: propose' "$f" && grep -q '^status: open' "$f" || continue
      echo; echo "--- $(basename "$f" .md) ---"; sed -n '/^---$/,/^---$/!p' "$f" | head -20
    done
    ;;
  *) echo "usage: lesson.sh add|bump|applied|rules|list|pending|queue|path" >&2; exit 64 ;;
esac
