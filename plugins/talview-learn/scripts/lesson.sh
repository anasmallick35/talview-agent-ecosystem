#!/usr/bin/env bash
# The lesson ledger. One file per lesson, classified by where it can be enforced.
#
#   lesson.sh capture <slug> <outcome> "<one line>"  in-session pushback, captured NOW
#   lesson.sh add <slug> <destination> <pr-url>    create from stdin (the lesson body)
#   lesson.sh bump <slug>                          seen again; 3+ flags for promotion
#   lesson.sh applied <slug> [note]                the enforcement now exists
#   lesson.sh list [status]
#   lesson.sh pending                              lessons needing a webclients PR
#   lesson.sh rules                                regenerate active-rules.md
#   lesson.sh queue add <pr-url> [repo]            a PR whose review is not harvested yet
#   lesson.sh queue list | queue done <pr-url>
#
# Destinations:
#   eslint-rule   mechanically detectable  -> dx/eslint-plugin       [webclients: PROPOSE]
#   hook          detectable at edit time  -> talview-core/hooks     [here: APPLY]
#   skill-rule    needs judgment           -> a skill's references/  [here: APPLY]
#   claude-md     seen 3+ times            -> CLAUDE.md              [webclients: PROPOSE]
#
# Storage lives in $HOME/.talview/lessons, NOT in the plugin directory. The plugin is
# installed into a version-pinned cache: writing lessons there means every release of
# this plugin silently abandons everything it learned. Override with TLV_LESSONS_DIR.

set -uo pipefail

: "${CLAUDE_PLUGIN_ROOT:=$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)}"
# Where the ledger lives, in order:
#   1. TLV_LESSONS_DIR            — explicit override, always wins
#   2. $CLAUDE_CONFIG_DIR/talview/lessons
#      Claude Code state that must outlive a container already lives under
#      CLAUDE_CONFIG_DIR; in a devcontainer it is pointed at a mounted volume. Following
#      it means several containers share one ledger and a rebuild does not erase what was
#      learned — without a change to the product repo's devcontainer.json, which the
#      whole team shares.
#   3. $HOME/.talview/lessons     — a plain workstation
tlv_lessons_dir() {
  if [ -n "${TLV_LESSONS_DIR:-}" ]; then printf '%s' "$TLV_LESSONS_DIR"; return; fi
  if [ -n "${CLAUDE_CONFIG_DIR:-}" ]; then printf '%s/talview/lessons' "$CLAUDE_CONFIG_DIR"; return; fi
  printf '%s/.talview/lessons' "${TLV_HOME:-$HOME}"
}
DIR="$(tlv_lessons_dir)"
RULES="$DIR/active-rules.md"
QUEUE="$DIR/harvest-queue.json"
mkdir -p "$DIR"

# One-time migrations, so neither a plugin upgrade nor a move onto a shared volume
# loses what was learned. Copy, never move: the old location staying intact means a
# half-finished migration is recoverable.
for legacy in "${CLAUDE_PLUGIN_ROOT}/lessons" "${TLV_HOME:-$HOME}/.talview/lessons"; do
  [ -d "$legacy" ] && [ "$legacy" != "$DIR" ] || continue
  for old in "$legacy"/*.md; do
    [ -f "$old" ] || continue
    case "$(basename "$old")" in active-rules.md) continue ;; esac
    [ -f "$DIR/$(basename "$old")" ] || { cp "$old" "$DIR/"; echo "migrated $(basename "$old") from $legacy" >&2; }
  done
done

# The rules file is DERIVED. It is what a session actually reads, so it is regenerated
# from the ledger rather than hand-edited — a rule that drifts from its lesson is a rule
# with no evidence behind it.
# A lesson written by `add` states its rule under "Proposed enforcement"; one written by
# `capture` states it under "What was argued". Reading only the first produced an empty
# bullet — a rule that injects nothing while looking like it worked.
rule_text() {
  local f="$1" t
  t="$(awk '/^## Proposed enforcement/{f=1;next} /^## /{f=0} f && NF' "$f" | head -2 | tr '\n' ' ')"
  [ -n "${t// /}" ] || t="$(awk '/^## What was argued/{f=1;next} /^## /{f=0} f && NF' "$f" | head -2 | tr '\n' ' ')"
  printf '%s' "$t"
}

regen_rules() {
  local n=0
  {
    echo "<!-- GENERATED by lesson.sh rules — do not edit. Source: $DIR/*.md -->"
    echo "# Rules learned from review"
    echo
    for f in "$DIR"/*.md; do
      [ -f "$f" ] || continue
      grep -q '^status: applied' "$f" || continue
      case "$(grep -m1 '^destination:' "$f" | cut -d' ' -f2-)" in
        skill-rule|claude-md) ;;
        *) continue ;;
      esac
      [ -n "$(rule_text "$f" | tr -d ' ')" ] || { echo "  skipped $(basename "$f" .md): applied but states no rule" >&2; continue; }
      n=$((n+1))
      printf -- "- **%s** (seen %s, %s): %s\n" \
        "$(basename "$f" .md)" \
        "$(grep -m1 '^seen:' "$f" | cut -d' ' -f2-)" \
        "$(grep -m1 '^source:' "$f" | cut -d' ' -f2-)" \
        "$(rule_text "$f")"
    done
    [ "$n" -eq 0 ] && echo "_No applied rules yet._"
  } > "$RULES"
  echo "$n"
}

case "${1:-list}" in
  # Feedback given in a chat session is not on GitHub and nothing else will remember it.
  # It is also the most common kind: a correction costs the human one sentence, so they
  # give far more of them than they ever write on a PR. Capture is deliberately cheap —
  # one line, no classification — because a capture step that takes thinking is a capture
  # step that gets skipped. /talview-learn:learn classifies drafts later.
  #
  # The outcome is recorded because being overruled is a different lesson from being
  # right: `rejected` means the human's instinct did not survive contact with the code,
  # and that is worth knowing before repeating the argument next time.
  capture)
    slug="${2:?slug}"; outcome="${3:?adopted|rejected|open}"; text="${4:?what was argued}"
    case "$outcome" in adopted|rejected|open) ;; *) echo "outcome must be adopted, rejected or open" >&2; exit 64 ;; esac
    f="$DIR/$slug.md"
    where="session$( [ -n "${TLV_BRANCH:-}" ] && printf ':%s' "$TLV_BRANCH" )"
    if [ -f "$f" ]; then
      n=$(( $(grep -m1 '^seen:' "$f" | awk '{print $2}') + 1 ))
      sed -i '' "s/^seen: .*/seen: $n/" "$f" 2>/dev/null || sed -i "s/^seen: .*/seen: $n/" "$f"
      printf '\n## Seen again (%s, %s)\n%s\n' "$where" "$outcome" "$text" >> "$f"
      echo "$slug seen $n time(s) — appended"
      if [ "$n" -ge 3 ]; then
        echo "  -> seen 3+ times: candidate for promotion to a CLAUDE.md hard rule."
      fi
      exit 0
    fi
    { echo "---"
      echo "slug: $slug"
      echo "destination: unclassified"
      echo "action: classify"
      echo "status: draft"
      echo "seen: 1"
      echo "outcome: $outcome"
      echo "source: $where"
      echo "---"
      echo
      echo "## What was argued"
      echo "$text"
      echo
      echo "## Outcome"
      case "$outcome" in
        adopted)  echo "The human's position was adopted. Treat it as the convention until contradicted." ;;
        rejected) echo "The human's position was NOT adopted after discussion. Record WHY, so the same argument is not re-run." ;;
        open)     echo "Unresolved when captured." ;;
      esac
      echo
      echo "## Still to do"
      echo "Classify with /talview-learn:learn: pick a destination, then \`lesson.sh applied\`."
    } > "$f"
    echo "captured $slug ($outcome) — draft, classify it at the end of the run"
    ;;

  drafts)
    found=0
    for f in "$DIR"/*.md; do
      [ -f "$f" ] || continue
      grep -q '^status: draft' "$f" || continue
      found=1
      printf '%-34s %-9s %s\n' "$(basename "$f" .md)" "$(grep -m1 '^outcome:' "$f" | cut -d' ' -f2-)" "$(sed -n '/^## What was argued/{n;p;}' "$f")"
    done
    if [ "$found" -eq 0 ]; then echo "_no unclassified captures_"; fi
    ;;

  add)
    slug="${2:?slug}"; dest="${3:?destination}"; pr="${4:-}"
    case "$dest" in
      eslint-rule|claude-md) applies="propose" ;;
      hook|skill-rule)       applies="apply" ;;
      *) echo "unknown destination '$dest'" >&2; exit 64 ;;
    esac
    f="$DIR/$slug.md"
    [ -f "$f" ] && { echo "lesson '$slug' exists — bump its count instead:"; grep -m1 '^seen:' "$f"; exit 1; }
    { echo "---"
      echo "slug: $slug"
      echo "destination: $dest"
      echo "action: $applies"
      echo "status: open"
      echo "seen: 1"
      echo "source: ${pr}"
      echo "---"
      echo
      cat
    } > "$f"
    echo "recorded $slug -> $dest ($applies)  [$DIR]"
    if [ "$applies" = "apply" ]; then
      echo "  -> write the rule or hook now, then: lesson.sh applied $slug"
    fi
    ;;

  bump)
    f="$DIR/${2:?slug}.md"; [ -f "$f" ] || { echo "no such lesson" >&2; exit 1; }
    n=$(( $(grep -m1 '^seen:' "$f" | awk '{print $2}') + 1 ))
    sed -i '' "s/^seen: .*/seen: $n/" "$f" 2>/dev/null || sed -i "s/^seen: .*/seen: $n/" "$f"
    echo "$2 seen $n time(s)"
    if [ "$n" -ge 3 ]; then
      echo "  -> seen 3+ times: candidate for promotion to a CLAUDE.md hard rule."
    fi
    regen_rules >/dev/null
    ;;

  applied)
    f="$DIR/${2:?slug}.md"; [ -f "$f" ] || { echo "no such lesson" >&2; exit 1; }
    note="${3:-}"
    # Marking an unclassified draft `applied` used to succeed and inject nothing: the
    # rules file only carries skill-rule and claude-md, so the lesson vanished silently.
    # Refuse instead. A no-op that reports success is the failure this tool exists to stop.
    dest="$(grep -m1 '^destination:' "$f" | cut -d' ' -f2-)"
    if [ "$dest" = "unclassified" ]; then
      echo "'$2' has no destination yet, so marking it applied would inject nothing." >&2
      echo "Classify it first — edit $f and set:" >&2
      echo "  destination: skill-rule   (injected at session start)" >&2
      echo "  destination: hook         (write the hook, then mark applied)" >&2
      echo "  destination: eslint-rule | claude-md   (propose to webclients; never auto-applied)" >&2
      exit 65
    fi
    case "$dest" in
      eslint-rule|claude-md)
        echo "'$2' is a $dest — it changes webclients and is a proposal, not something to apply here." >&2
        echo "Leave it open and raise it with: lesson.sh pending" >&2
        exit 65 ;;
    esac
    sed -i '' "s/^status: .*/status: applied/" "$f" 2>/dev/null || sed -i "s/^status: .*/status: applied/" "$f"
    [ -n "$note" ] && printf '\n## Enforcement landed\n%s\n' "$note" >> "$f"
    echo "$2 marked applied; $(regen_rules) rule(s) now active"
    ;;

  rules)
    n="$(regen_rules)"
    echo "$RULES — $n active rule(s)"
    ;;

  path) echo "$DIR" ;;

  queue)
    sub="${2:-list}"
    [ -f "$QUEUE" ] || echo '[]' > "$QUEUE"
    case "$sub" in
      add)
        url="${3:?pr url}"; repo="${4:-}"
        jq --arg u "$url" --arg r "$repo" \
          'if any(.[]; .url == $u) then . else . + [{url:$u, repo:$r, harvested:false}] end' \
          "$QUEUE" > "$QUEUE.tmp.$$" && mv "$QUEUE.tmp.$$" "$QUEUE"
        echo "queued for harvest once review lands: $url"
        ;;
      done)
        url="${3:?pr url}"
        jq --arg u "$url" 'map(if .url == $u then .harvested = true else . end)' \
          "$QUEUE" > "$QUEUE.tmp.$$" && mv "$QUEUE.tmp.$$" "$QUEUE"
        echo "marked harvested: $url"
        ;;
      list)
        jq -r '[.[] | select(.harvested == false)] | if length == 0 then "_nothing awaiting harvest_" else .[].url end' "$QUEUE"
        ;;
      count) jq -r '[.[] | select(.harvested == false)] | length' "$QUEUE" ;;
      *) echo "usage: lesson.sh queue add|list|done|count" >&2; exit 64 ;;
    esac
    ;;

  list)
    printf "%-34s %-14s %-9s %-6s %s\n" SLUG DESTINATION ACTION SEEN STATUS
    for f in "$DIR"/*.md; do
      [ -f "$f" ] || continue
      [ "$(basename "$f")" = "active-rules.md" ] && continue
      printf "%-34s %-14s %-9s %-6s %s\n" \
        "$(basename "$f" .md)" \
        "$(grep -m1 '^destination:' "$f" | cut -d' ' -f2-)" \
        "$(grep -m1 '^action:' "$f" | cut -d' ' -f2-)" \
        "$(grep -m1 '^seen:' "$f" | cut -d' ' -f2-)" \
        "$(grep -m1 '^status:' "$f" | cut -d' ' -f2-)"
    done
    ;;

  pending)
    echo "Lessons that need a change in the PRODUCT repo — these are proposals, not applied:"
    for f in "$DIR"/*.md; do
      [ -f "$f" ] || continue
      grep -q '^action: propose' "$f" && grep -q '^status: open' "$f" || continue
      echo; echo "--- $(basename "$f" .md) ---"; sed -n '/^---$/,/^---$/!p' "$f" | head -20
    done
    ;;
  *) echo "usage: lesson.sh capture|drafts|add|bump|applied|rules|list|pending|queue|path" >&2; exit 64 ;;
esac
